"""§12.1 ABJ-trace anomalies as provable impossibility proofs.

Physics origin (Adler-Bell-Jackiw 1969; 't Hooft 1980): a classical
symmetry generated by ``T^a`` survives quantization iff the anomaly
polynomial

    A^{abc} = Tr( T^a {T^b, T^c} )

vanishes for every triple ``(a, b, c)``. A nonzero anomaly is a *positive
obstruction*: no consistent quantum theory carries that symmetry. This is
how physicists prove certain theories are impossible — by detecting an
obstruction in the operator algebra, not by exhaustive search.

QPCN realization (spec §12.1): the typing Hamiltonian's per-rule factored
projectors are **leaf-local generators** that classically commute with the
ground-state manifold (well-typed programs). An ill-typed program breaks
the symmetry not by vacuum choice (Goldstone, §12.6) and not by branch
multiplicity (topological degeneracy, §12.3) but by an algebraic
obstruction in the projector triple ``Tr( P_kind { P_type, P_value } )``
evaluated on the leaf marginal. When the typing rule's kind/type/value
expectations cannot simultaneously align with their well-typed values,
the ABJ trace fires and the theorem is provably unprovable.

This module is operator-algebraic (§1.1 anti-shortcut): symmetry
generators are read off the typing Hamiltonian's factored projector
operators, NOT from the AST. The anomaly trace is evaluated on the real
MERA leaf marginals through ``state.leaf_marginal`` and
``mera_window_expectation_factored`` — never via dense ``16**k`` operator
construction (§1.3), never via AST symbol parsing.

Cost: per generator, a constant number of factored window expectations
on the state, polynomial in ``meta.n_nodes`` and the number of rules. The
trace itself reduces to products of single-leaf expectations on a
product MERA via the §1.2 factorization, so the whole computation is
``O(N_rules · N_nodes)`` window evaluations — cheap relative to the
proof search.
"""
