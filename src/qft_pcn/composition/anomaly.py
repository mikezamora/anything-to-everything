@dataclass(frozen=True)
class AnomalyCertificate:
    """A certificate that a theorem is anomalously obstructed.

    ``generators`` lists every (rule_id, node) generator whose ABJ trace
    exceeded the floor, sorted by trace magnitude (descending) for
    deterministic surfacing. ``total_anomaly`` is the sum of those
    traces — the global obstruction mass. ``is_obstructed`` is True iff
    at least one generator fired.

    This is the §12.1 "impossibility certificate": a positive result
    (the theorem is provably unprovable from these axioms), distinct
    from a search failure.
    """
    is_obstructed: bool
    total_anomaly: float
    generators: tuple[tuple[str, int, float], ...]
    floor: float


def anomaly_polynomial(
    typing_H: MeraTypingHamiltonian,
    state: MERA,
    floor: float = DEFAULT_ANOMALY_FLOOR,
) -> AnomalyCertificate:
    """The full anomaly polynomial for ``state`` under ``typing_H``.

    Evaluates :func:`compute_anomaly` on every generator extracted from
    ``typing_H``, sums the traces above ``floor``, and returns a
    certificate. The polynomial is

        A(psi) = Σ_G  A(G; psi)

    over the candidate symmetry generators. Determinism: with a fixed
    (typing_H, state, floor) the generator list and per-generator trace
    are deterministic, and the certificate is byte-identical across runs
    (sort tie-breaks on (rule_id, node)).
    """
    generators = extract_symmetries(typing_H)
    fired: list[tuple[str, int, float]] = []
    total = 0.0
    for G in generators:
        a = compute_anomaly(G, state)
        if a > floor:
            fired.append((G.rule_id, G.node, a))
            total += a
    fired.sort(key=lambda r: (-r[2], r[0], r[1]))
    return AnomalyCertificate(
        is_obstructed=len(fired) > 0,
        total_anomaly=float(total),
        generators=tuple(fired),
        floor=floor,
    )


def is_anomalously_obstructed(
    theorem_state: MERA,
    typing_H: MeraTypingHamiltonian,
    floor: float = DEFAULT_ANOMALY_FLOOR,
) -> bool:
    """Top-level §12.1 check: is the theorem genuinely unprovable?

    Returns True iff ``anomaly_polynomial(typing_H, theorem_state)``
    has at least one generator above ``floor``. Equivalent to

        anomaly_polynomial(typing_H, state).is_obstructed

    but provided as a one-liner for the spec §12.1 acceptance test
    contract.

    A True return is a *positive* result: the theorem cannot be proved
    from these axioms (the obstruction is intrinsic to the constraint
    algebra, not a search failure). A False return does not certify
    provability — it only says §12.1 found no obstruction; proof search
    must still be attempted (or §12.6 Goldstone diagnostics consulted
    for missing-lemma candidates).
    """
    return anomaly_polynomial(typing_H, theorem_state, floor=floor).is_obstructed


