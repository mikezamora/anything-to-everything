def mine_symmetries(
    library: LemmaLibrary,
    degeneracy_tol: float = DEFAULT_DEGENERACY_TOL,
) -> list[Symmetry]:
    """Mine continuous symmetries from a real LemmaLibrary (spec §12.18 step 2).

    Operator-algebraic procedure:
      1. Load every lemma's fingerprint (leaf-bond Gram spectrum, §4.3).
      2. Build the library covariance operator
         ``C = sum_i |fp_i> <fp_i|``.
      3. Diagonalize ``C``. Each ``r >= 2`` degenerate eigenspace yields
         an so(r) family of continuous symmetries; emit the canonical
         so(2)-style generator embedded in that eigenspace.

    A trivial library (empty or single lemma) has no degenerate
    eigenspaces -> returns ``[]``.

    Spec §12.18 substrate contract:
      * Symmetry generators live in the leaf-bond Gram-spectrum space --
        the real operator-algebraic invariant of the MERA (§4.3), NOT in
        any AST / surface-syntax space.
      * Degenerate-eigenspace detection is the entire mining algorithm;
        no AST pattern matching, no heuristic rule lookup.
    """
    if degeneracy_tol < 0:
        raise ValueError(
            f"degeneracy_tol must be >= 0, got {degeneracy_tol}")

    lemma_ids = list(library.all_ids())
    if len(lemma_ids) < 2:
        # Single or empty library: no possible continuous symmetry.
        return []

    lemmas: list[Lemma] = [library.load(lid) for lid in lemma_ids]
    fps = [np.asarray(lem.fingerprint, dtype=float) for lem in lemmas]
    C = _library_covariance(fps)

    eigvals, eigvecs = np.linalg.eigh(C)  # ascending eigenvalues
    blocks = _degenerate_blocks(eigvals, degeneracy_tol)
    if not blocks:
        return []

    # For each degenerate block, build the canonical so(2)-style
    # generator and identify which lemmas physically project onto it.
    # A lemma "supports" the symmetry if its fingerprint has non-trivial
    # projection (L2 weight) onto the degenerate eigenspace.
    symmetries: list[Symmetry] = []
    for block in blocks:
        idxs = np.asarray(block, dtype=int)
        V = eigvecs[:, idxs]  # (FINGERPRINT_DIM, r)
        A = _so_generator_in_block(V)
        block_eigs = eigvals[idxs]
        # Lemmas supporting the block: those with non-negligible
        # projection onto V. Threshold derives from the same tolerance --
        # a projection weight below sqrt(degeneracy_tol) is treated as
        # numerical leak, not genuine support.
        proj_thresh = max(np.sqrt(degeneracy_tol), 1e-9)
        support: list[str] = []
        for lem in lemmas:
            fp = np.asarray(lem.fingerprint, dtype=float)
            # Squared projection onto the eigenspace.
            coeffs = V.T @ fp
            weight = float(np.sum(coeffs * coeffs))
            if weight >= proj_thresh:
                support.append(lem.lemma_id)
        # A genuine continuous symmetry must rotate >= 2 lemmas.
        if len(support) < 2:
            continue
        symmetries.append(Symmetry(
            generator=A,
            eigenspace_dim=len(idxs),
            eigenvalue=float(np.mean(block_eigs)),
            invariance_residual=float(np.max(block_eigs) - np.min(block_eigs)),
            support_lemma_ids=tuple(sorted(support)),
        ))
    return symmetries


def build_noether_current(
    symmetry: Symmetry,
    library: LemmaLibrary | None = None,
) -> NoetherCurrent:
    """Constructive Noether procedure (spec §12.18 step 3).

    Given a continuous symmetry generator ``A`` (anti-Hermitian), the
    Noether current is

        J = i * A                   (Hermitian)

    By construction ``[H_lib, J] = i * [C, A] = 0`` since ``A`` commutes
    with the library covariance operator ``C`` (it lives entirely within
    a degenerate eigenspace).

    If ``library`` is supplied, the conservation residual
    ``||[C, J]||_F`` is computed against the actual library covariance
    operator at the time of the call (a fresh read-through). Otherwise
    the residual is set to zero by construction.
    """
    A = np.asarray(symmetry.generator, dtype=float)
    # J = i * A. For A real anti-symmetric, J is purely imaginary
    # anti-Hermitian -> Hermitian after the i factor.
    J = 1j * A

    if library is None:
        residual = 0.0
    else:
        lemma_ids = list(library.all_ids())
        if not lemma_ids:
            residual = 0.0
        else:
            fps = [np.asarray(library.load(lid).fingerprint, dtype=float)
                   for lid in lemma_ids]
            C = _library_covariance(fps)
            # [C, J] = C J - J C. Frobenius norm.
            comm = C @ J - J @ C
            residual = float(np.linalg.norm(comm, ord="fro"))

    return NoetherCurrent(
        current=J,
        symmetry=symmetry,
        conservation_residual=residual,
    )
